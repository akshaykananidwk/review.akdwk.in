-- AK Earn connector (earn.akdwk.in)
--
-- Two tables, both additive. Nothing existing is altered.
--
-- ak_outbox
--   Money events are written here inside the request and delivered by
--   cron a moment later. The customer's signup or payment therefore
--   never waits on earn.akdwk.in: a local INSERT takes microseconds,
--   while the SDK allows a 3s connect + 6s read timeout that would
--   otherwise sit in the middle of the Razorpay success callback.
--   It doubles as the admin panel's event log — status, attempts and
--   the last error are all on the row.
--
-- ak_daily_visits
--   One counter row per day for the public marketing pages, so the
--   daily stats push can report real visitor numbers instead of zero.
--   The browser beacon reports to the master separately; this is our
--   own independent count.

CREATE TABLE IF NOT EXISTS ak_outbox (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    -- event_id is generated by the SDK and is deterministic, so the same
    -- real-world event always produces the same id. UNIQUE here stops us
    -- queueing it twice; the master also ignores duplicates, giving two
    -- independent guarantees against double counting.
    event_id VARCHAR(100) NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    sdk_call VARCHAR(40) NOT NULL,
    payload_json MEDIUMTEXT NOT NULL,
    ref_code VARCHAR(20) NULL,
    visitor_id CHAR(32) NULL,
    amount DECIMAL(12,2) NULL,
    status ENUM('pending','sent','failed','skipped') NOT NULL DEFAULT 'pending',
    attempts INT UNSIGNED NOT NULL DEFAULT 0,
    last_error VARCHAR(500) NULL,
    next_attempt_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at DATETIME NULL,
    UNIQUE KEY uk_ak_outbox_event (event_id),
    KEY idx_ak_outbox_pending (status, next_attempt_at),
    KEY idx_ak_outbox_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ak_daily_visits (
    visit_date DATE NOT NULL PRIMARY KEY,
    visits INT UNSIGNED NOT NULL DEFAULT 0,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Register the two connector jobs with the existing cron scheduler so
-- they run from the one master cron, like every other background task.
-- CronService::syncRegistry() inserts them on the next tick; these rows
-- only pre-set sensible schedules if the table is already present.
INSERT INTO system_settings (setting_key, setting_value, value_type, is_encrypted)
SELECT 'ak_earn_backfill_done', '0', 'bool', 0
FROM DUAL
WHERE NOT EXISTS (
    SELECT 1 FROM system_settings WHERE setting_key = 'ak_earn_backfill_done'
);
